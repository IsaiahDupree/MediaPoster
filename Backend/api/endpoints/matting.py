@router.get("/models")
async def list_models():
    """List available matting models."""
    return {
        "models": [
            {
                "id": model.value,
                "name": model.name,
                "description": _get_model_description(model)
            }
            for model in MattingModel
        ]
    }


def _get_model_description(model: MattingModel) -> str:
    """Get description for model."""
    descriptions = {
        MattingModel.RVM: "Robust Video Matting - Highest quality, temporal memory, real-time capable",
        MattingModel.MEDIAPIPE: "MediaPipe Selfie Segmentation - Fast, lightweight, works on CPU",
        MattingModel.BACKGROUND_MATTING_V2: "BackgroundMattingV2 - Best with clean background plate",
        MattingModel.REMBG: "rembg - Simple batch processing, good for images",
        MattingModel.SAM2: "SAM 2 - Advanced segmentation, specific objects",
    }
    return descriptions.get(model, f"{model.value} matting model")

